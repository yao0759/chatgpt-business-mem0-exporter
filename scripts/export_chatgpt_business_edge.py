def _strip_language_from_code_text(code_text: str, language: str) -> str:
    """Remove a UI language label if it leaked into the beginning of code."""
    text = str(code_text or "").replace("\r\n", "\n").replace("\r", "\n")
    lang = _normalize_export_language(language)
    label = _code_language_label(lang)

    lines = text.split("\n")
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()

    if lines and lines[0].strip().lower() == label.lower():
        lines.pop(0)

    text = "\n".join(lines)

    # Handle "Bashcat ..." / "YAML---" while avoiding a real "bash file.sh".
    if label and text.startswith(label) and len(text) > len(label):
        next_char = text[len(label)]
        if not next_char.isspace():
            text = text[len(label):]

    return text.strip("\n")


def _render_export_code_block(block: dict, block_id: str) -> str:
    language = _normalize_export_language(block.get("language") or "")
    label = _code_language_label(language)
    code_text = _strip_language_from_code_text(
        str(block.get("text") or ""),
        language,
    )

    if not code_text.strip():
        return (
            '<div class="code-block code-missing">'
            '<div class="code-head">'
            f'<span class="code-language">{html_lib.escape(label)}</span>'
            '</div>'
            '<div class="code-missing-text">'
            '此代码块没有提取到正文。可运行 --repair-html-code 重新从原会话抓取。'
            '</div></div>'
        )

    return (
        f'<div class="code-block" id="{html_lib.escape(block_id, quote=True)}">'
        '<div class="code-head">'
        f'<span class="code-language">{html_lib.escape(label)}</span>'
        '<button class="copy-code" type="button">复制</button>'
        '</div>'
        '<pre><code>'
        f'{html_lib.escape(code_text)}'
        '</code></pre>'
        '</div>'
    )


def _replace_code_placeholders(clean_html: str, code_blocks: list[dict] | None, message_id: str) -> str:
    blocks = list(code_blocks or [])
    if not blocks:
        # Old JSON: leave non-empty pre blocks alone; empty ones will be hidden
        # by CSS rather than shown as giant dark bars.
        return clean_html

    # Replace only our explicit markers.  Do not replace ordinary <pre>
    # elements: older exports may contain legitimate, already-populated code.
    # Use the saved index instead of a positional cursor so unrelated <pre>
    # elements cannot shift subsequent code blocks.
    pattern = re.compile(
        r'''<pre\s+data-export-code-index=["'](\d+)["']\s*></pre>''',
        flags=re.I,
    )
    used: set[int] = set()

    def repl(match):
        index = int(match.group(1))
        if index < 0 or index >= len(blocks):
            return (
                '<div class="code-block code-missing">'
                '<div class="code-missing-text">代码块索引无效，无法恢复。</div>'
                '</div>'
            )
        used.add(index)
        return _render_export_code_block(
            blocks[index],
            f"{message_id}-code-{index + 1}",
        )

    rendered = pattern.sub(repl, clean_html)

    # If ChatGPT changed its DOM and there are more extracted blocks than
    # placeholders, append them rather than silently losing code.
    missing = [index for index in range(len(blocks)) if index not in used]
    if missing:
        extra = []
        for index in missing:
            extra.append(
                _render_export_code_block(
                    blocks[index],
                    f"{message_id}-code-{index + 1}",
                )
            )
        rendered += (
            '<div class="content-warning">'
            '部分代码块在原消息 HTML 中没有位置标记，已附加在消息末尾。'
            '</div>'
            + "".join(extra)
        )

    return rendered


def sanitize_message_html(
    raw_html: str,
    fallback_text: str = "",
    code_blocks: list[dict] | None = None,
    message_id: str = "message",
) -> str:
    clean, _broken = clean_message_html(raw_html, fallback_text=fallback_text)
    return _replace_code_placeholders(clean, code_blocks, message_id)


def _file_href_for_html(local_path: str, html_path: Path) -> str:
    if not local_path:
        return ""
    try:
        p = Path(local_path)
        rel = os.path.relpath(str(p), str(html_path.parent)).replace("\\", "/")
        return quote(rel, safe="/:._-~")
    except Exception:
        return ""


def _render_generated_files_html(record: dict, assistant_counter: int, html_path: Path) -> str:
    matched = []
    for f in record.get("generated_files", []):
        try:
            if int(f.get("assistant_message_index")) == assistant_counter:
                matched.append(f)
        except Exception:
            continue
    if not matched:
        return ""

    items = []
    for f in matched:
        filename = str(f.get("filename") or "generated_file")
        size = f.get("size", "?")
        digest = str(f.get("sha256") or "")
        local_path = str(f.get("local_path") or "")
        href = _file_href_for_html(local_path, html_path)
        file_label = html_lib.escape(filename)
        if href:
            file_label = f'<a href="{html_lib.escape(href, quote=True)}" target="_blank" rel="noopener">{file_label}</a>'
        sha = f'<span class="file-sha">SHA256 {html_lib.escape(digest)}</span>' if digest else ""
        items.append(
            '<li class="generated-file">'
            f'<span class="file-icon">📄</span><span class="file-name">{file_label}</span>'
            f'<span class="file-meta">{html_lib.escape(str(size))} bytes</span>{sha}'
            '</li>'
        )

    return (
        '<section class="generated-files"><div class="generated-title">ChatGPT 生成文件</div>'
        '<ul>' + "".join(items) + '</ul></section>'
    )


