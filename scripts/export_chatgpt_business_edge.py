_SAFE_HTML_TAGS = {
    "p", "div", "span", "pre", "code", "strong", "b", "em", "i", "u",
    "ul", "ol", "li", "h1", "h2", "h3", "h4", "h5", "h6", "blockquote",
    "table", "thead", "tbody", "tfoot", "tr", "th", "td", "a", "img",
    "br", "hr", "details", "summary", "sup", "sub", "mark", "kbd", "s",
    "del", "figure", "figcaption"
}
_SAFE_VOID_TAGS = {"br", "hr", "img"}
_SAFE_HTML_ATTRS = {
    "a": {"href", "title"},
    "img": {"src", "alt", "title", "width", "height"},
    "code": {"class", "data-language", "data-lang"},
    "pre": {"class", "data-language", "data-lang"},
    "span": {"class"},
    "div": {"class"},
    "table": {"class"},
    "th": {"colspan", "rowspan"},
    "td": {"colspan", "rowspan"},
}


class _SafeHtmlSanitizer(HTMLParser):
    """Keep semantic message HTML while dropping ChatGPT UI controls/scripts."""

    DROP_CONTENT_TAGS = {"script", "style", "noscript", "svg", "button"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out: list[str] = []
        self.drop_depth = 0
        self.open_tags: list[str] = []

    def handle_starttag(self, tag, attrs):
        tag = tag.lower()
        if self.drop_depth:
            self.drop_depth += 1
            return
        if tag in self.DROP_CONTENT_TAGS:
            self.drop_depth = 1
            return
        if tag not in _SAFE_HTML_TAGS:
            return

        allowed = _SAFE_HTML_ATTRS.get(tag, set())
        clean_attrs = []
        for key, value in attrs:
            key = key.lower()
            if key not in allowed or value is None:
                continue
            value = str(value)
            if key in {"href", "src"} and re.match(r"^\s*(?:javascript|vbscript):", value, re.I):
                continue
            if key == "class":
                tokens = [
                    t for t in value.split()
                    if re.match(r"^(?:language-|lang-|hljs|highlight|whitespace-pre|prose)", t, re.I)
                ]
                value = " ".join(tokens)
                if not value:
                    continue
            clean_attrs.append((key, value))

        attrs_text = "".join(
            f' {html_lib.escape(k, quote=True)}="{html_lib.escape(v, quote=True)}"'
            for k, v in clean_attrs
        )
        self.out.append(f"<{tag}{attrs_text}>")
        if tag not in _SAFE_VOID_TAGS:
            self.open_tags.append(tag)

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag.lower() not in _SAFE_VOID_TAGS:
            self.handle_endtag(tag)

    def handle_endtag(self, tag):
        tag = tag.lower()
        if self.drop_depth:
            self.drop_depth -= 1
            return
        if tag not in _SAFE_HTML_TAGS or tag in _SAFE_VOID_TAGS:
            return
        if tag in self.open_tags:
            while self.open_tags:
                current = self.open_tags.pop()
                self.out.append(f"</{current}>")
                if current == tag:
                    break

    def handle_data(self, data):
        if not self.drop_depth and data:
            self.out.append(html_lib.escape(data))

    def get_html(self) -> str:
        while self.open_tags:
            self.out.append(f"</{self.open_tags.pop()}>")
        return "".join(self.out)



def _safe_url_attr(value: str) -> str:
    value = str(value or "").strip()
    if re.match(r"^(?:javascript|vbscript|data:text/html)", value, re.I):
        return ""
    return value


def _clean_html_node(node, *, inside_pre: bool = False) -> str:
    if isinstance(node, str):
        return html_lib.escape(node)

    tag = node.tag

    if tag == "root":
        return "".join(_clean_html_node(c) for c in node.children)

    if tag in {"script", "style", "noscript", "svg", "button"}:
        return ""

    if tag == "pre":
        # V8.2 replaces each live ChatGPT code block with an indexed, empty
        # placeholder before sanitizing the message HTML.  The old sanitizer
        # treated that deliberately-empty <pre> as a lost code block and
        # removed it.  With no placeholders left, _replace_code_placeholders()
        # could only append every recovered block to the end of the message.
        # Preserve the marker verbatim so the code is restored in DOM order.
        export_index = _node_attr(node, "data-export-code-index").strip()
        if export_index.isdigit():
            return f'<pre data-export-code-index="{html_lib.escape(export_index, quote=True)}"></pre>'

        code_node = _find_first(node, "code")
        source = code_node if code_node is not None else node
        code_text = _node_text(source, preserve_breaks=True)
        code_text = code_text.replace("\r\n", "\n").replace("\r", "\n").strip("\n")

        # Old V5 JSON can contain <pre> shells whose code text was already
        # destroyed during extraction. Do NOT render those as empty black bars.
        if not code_text.strip():
            return ""

        lang = _infer_code_language(node, code_node)
        lang_attr = (
            f' class="language-{html_lib.escape(lang, quote=True)}"'
            if lang else ""
        )
        pre_lang = (
            f' data-language="{html_lib.escape(lang, quote=True)}"'
            if lang else ""
        )
        return (
            f"<pre{pre_lang}><code{lang_attr}>"
            + html_lib.escape(code_text)
            + "</code></pre>"
        )

    if tag == "code":
        code_text = _node_text(node, preserve_breaks=True)
        return "<code>" + html_lib.escape(code_text) + "</code>"

    if tag in {"strong", "b"}:
        return "<strong>" + "".join(_clean_html_node(c) for c in node.children) + "</strong>"
    if tag in {"em", "i"}:
        return "<em>" + "".join(_clean_html_node(c) for c in node.children) + "</em>"
    if tag in {"s", "strike", "del"}:
        return "<del>" + "".join(_clean_html_node(c) for c in node.children) + "</del>"
    if tag == "u":
        return "<u>" + "".join(_clean_html_node(c) for c in node.children) + "</u>"
    if tag in {"sup", "sub", "mark", "kbd"}:
        return f"<{tag}>" + "".join(_clean_html_node(c) for c in node.children) + f"</{tag}>"

    if tag == "a":
        href = _safe_url_attr(_node_attr(node, "href"))
        body = "".join(_clean_html_node(c) for c in node.children)
        if not href:
            return body
        title = _node_attr(node, "title")
        title_attr = f' title="{html_lib.escape(title, quote=True)}"' if title else ""
        return (
            f'<a href="{html_lib.escape(href, quote=True)}"{title_attr} '
            f'target="_blank" rel="noopener">{body}</a>'
        )

    if tag == "img":
        src = _safe_url_attr(_node_attr(node, "src"))
        if not src:
            return html_lib.escape(_node_attr(node, "alt"))
        alt = html_lib.escape(_node_attr(node, "alt"), quote=True)
        title = _node_attr(node, "title")
        title_attr = f' title="{html_lib.escape(title, quote=True)}"' if title else ""
        return (
            f'<img src="{html_lib.escape(src, quote=True)}" alt="{alt}"'
            f'{title_attr} loading="lazy">'
        )

    if tag == "br":
        return "<br>"
    if tag == "hr":
        return "<hr>"

    if tag in {"h1", "h2", "h3", "h4", "h5", "h6",
               "p", "blockquote", "ul", "ol", "li",
               "table", "thead", "tbody", "tfoot", "tr",
               "figure", "figcaption", "details", "summary"}:
        body = "".join(_clean_html_node(c) for c in node.children)
        return f"<{tag}>{body}</{tag}>"

    if tag in {"th", "td"}:
        attrs = []
        for key in ("colspan", "rowspan"):
            value = _node_attr(node, key)
            if value and str(value).isdigit():
                attrs.append(f' {key}="{html_lib.escape(str(value), quote=True)}"')
        body = "".join(_clean_html_node(c) for c in node.children)
        return f"<{tag}{''.join(attrs)}>{body}</{tag}>"

    # ChatGPT uses many nested div/span wrappers. Do not preserve the wrappers
    # unless they are needed for user pasted-text whitespace.
    cls = _node_attr(node, "class").lower()
    body = "".join(_clean_html_node(c) for c in node.children)
    if "whitespace-pre-wrap" in cls or "whitespace-pre" in cls:
        return f'<div class="preserve-whitespace">{body}</div>'
    return body


def _analyze_pre_blocks(raw_html: str) -> tuple[int, int]:
    """Return (total_pre_blocks, empty_pre_blocks) from stored message HTML."""
    if not raw_html or "<pre" not in raw_html.lower():
        return 0, 0
    try:
        parser = _HtmlTreeParser()
        parser.feed(raw_html)
        parser.close()
        total = 0
        empty = 0
        for node in _walk_nodes(parser.root):
            if node.tag != "pre":
                continue
            # An indexed export placeholder is intentionally empty.  It is
            # paired with msg["code_blocks"] and is not evidence of code loss.
            if _node_attr(node, "data-export-code-index").strip().isdigit():
                continue
            total += 1
            code_node = _find_first(node, "code")
            source = code_node if code_node is not None else node
            if not _node_text(source, preserve_breaks=True).strip():
                empty += 1
        return total, empty
    except Exception:
        return 0, 0



def record_has_code_blocks(record: dict) -> bool:
    """Return True when an exported session contains one or more code blocks.

    V8+ records normally carry a separate ``code_blocks`` list.  Older records
    may only contain ``<pre>`` elements in their saved HTML, so support both.
    """
    for msg in record.get("messages", []):
        blocks = msg.get("code_blocks")
        if isinstance(blocks, list) and blocks:
            return True
        raw_html = str(msg.get("html") or "")
        if re.search(r"<pre(?:\s|>)", raw_html, flags=re.I):
            return True
    return False


def record_has_v6_code_format_symptom(record: dict) -> bool:
    """
    Detect common V6 formatting symptoms:
      Bashcat ...
      BashCUDA_VISIBLE_DEVICES...
      YAML---
      or a shell block that contains several backslash continuations but
      almost no preserved newlines.
    """
    prefix_re = re.compile(
        r"^(?:Bash|Shell|PowerShell|Python|JavaScript|TypeScript|JSONL?|YAML|YML|XML|HTML|CSS|SQL|Dockerfile|Nginx|TOML|INI|Markdown|Console|Terminal)(?=\\S)",
        flags=re.I,
    )

    for msg in record.get("messages", []):
        raw_html = str(msg.get("html") or "")
        if "<pre" not in raw_html.lower():
            continue

        try:
            parser = _HtmlTreeParser()
            parser.feed(raw_html)
            parser.close()
            for node in _walk_nodes(parser.root):
                if node.tag != "pre":
                    continue
                code_node = _find_first(node, "code")
                source = code_node if code_node is not None else node
                code = _node_text(source, preserve_breaks=True).replace("\\r\\n", "\\n").replace("\\r", "\\n")
                stripped = code.strip()

                if prefix_re.search(stripped):
                    return True

                # Typical collapsed multiline shell command:
                # command \\   --arg ... \\   --arg ...
                if stripped.count("\\n") <= 1 and len(re.findall(r"\\\\\\s+", stripped)) >= 2:
                    return True
        except Exception:
            continue

    return False


def record_needs_content_repair(record: dict) -> bool:
    """Detect the V5 aria-hidden/code-loss symptom."""
    for msg in record.get("messages", []):
        raw_html = str(msg.get("html") or "")
        total, empty = _analyze_pre_blocks(raw_html)
        if total and empty:
            # One genuinely empty code block is possible, but many empty <pre>
            # blocks or an assistant turn consisting mostly of empty <pre>s is
            # a strong signature of the old extractor bug.
            if empty >= 2 or (empty == total and str(msg.get("role")) == "assistant"):
                return True
    return False


def clean_message_html(raw_html: str, fallback_text: str = "") -> tuple[str, bool]:
    """Return (semantic_html, old_export_code_loss_detected)."""
    total_pre, empty_pre = _analyze_pre_blocks(raw_html)
    broken = bool(total_pre and empty_pre)

    if raw_html and raw_html.strip():
        try:
            parser = _HtmlTreeParser()
            parser.feed(raw_html)
            parser.close()
            clean = _clean_html_node(parser.root).strip()
            if clean:
                if broken:
                    warning = (
                        '<div class="content-warning">'
                        '⚠ 检测到此消息包含旧版导出时丢失的空代码块。'
                        '空代码块已隐藏；要恢复代码正文，请运行 --repair-content。'
                        '</div>'
                    )
                    return warning + clean, True
                return clean, False
        except Exception:
            pass

    fallback = str(fallback_text or "")
    if broken:
        warning = (
            '<div class="content-warning">'
            '⚠ 此消息的代码块正文在旧版导出时已丢失。'
            '请运行 --repair-code-format 从原 ChatGPT 会话重新抓取，无需扫描会话列表。'
            '</div>'
        )
        if fallback.strip():
            return warning + '<pre class="plain-text">' + html_lib.escape(fallback) + '</pre>', True
        return warning, True

    return '<pre class="plain-text">' + html_lib.escape(fallback) + '</pre>', False



