    html_name = f"{cid}__{safe_filename(title)}.html"
    json_name = f"{cid}__{safe_filename(title)}.json"

    md_path = out_dir / "markdown" / md_name
    html_path = out_dir / "html" / html_name
    json_path = out_dir / "json" / json_name

