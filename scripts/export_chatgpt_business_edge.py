"""
Export ChatGPT Business conversations from the user's CURRENT, already logged-in
Microsoft Edge session, and download files generated by ChatGPT in assistant
messages.

Windows-oriented workflow:
1. Keep your normal Edge open and logged into ChatGPT Business.
2. In Edge open: edge://inspect
3. Open "Remote debugging" and enable "Allow remote debugging for this browser instance".
4. Run this script.

The script attaches to the running Edge over CDP. It does NOT launch a separate
browser profile and does NOT ask you to log in again.

Install:
    py -m pip install -U playwright

Run:
    py export_chatgpt_business_edge_live.py

Notes:
- Only conversations accessible to the signed-in account/workspace can be read.
- Only assistant-generated files that are still represented/downloadable in the
  rendered conversation can be saved.
- User-uploaded files are deliberately ignored because downloads are collected
  only from assistant message containers.
- This is UI automation. ChatGPT UI markup can change, so selectors may need
  occasional updates.
"""

