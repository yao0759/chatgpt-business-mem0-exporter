async def capture_native_mhtml(page, output_path: Path) -> None:
    """
    Capture the CURRENT Edge/Chromium page as MHTML via CDP Page.captureSnapshot.

    The browser serializes what it is actually rendering. We do not rebuild
    ChatGPT message HTML, rewrite code blocks, or convert the conversation DOM.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)

    try:
        await page.bring_to_front()
    except Exception:
        pass

    try:
        await page.wait_for_load_state("domcontentloaded", timeout=15000)
    except Exception:
        pass

    # Touch both ends of the conversation to give lazy-rendered content/resources
    # a chance to materialize. This is NOT a sidebar/history scan.
    try:
        await page.evaluate("window.scrollTo(0, 0)")
        await page.wait_for_timeout(250)
        await page.evaluate("window.scrollTo(0, document.body.scrollHeight)")
        await page.wait_for_timeout(700)
    except Exception:
        pass

    cdp = await page.context.new_cdp_session(page)
    try:
        result = await cdp.send("Page.captureSnapshot", {"format": "mhtml"})
        data = result.get("data", "")
        if not data:
            raise RuntimeError("Page.captureSnapshot 返回空数据")
        atomic_write_text(output_path, data)
    finally:
        try:
            await cdp.detach()
        except Exception:
            pass


