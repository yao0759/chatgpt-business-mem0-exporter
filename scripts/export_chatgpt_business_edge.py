def rerender_all_html(out_dir: Path) -> tuple[int, int, int, Path]:
    """Build standalone HTML from already exported JSON sessions only.

    No Edge connection, no sidebar scan, no network access, no file redownload.
    """
    json_dir = out_dir / "json"
    html_dir = out_dir / "html"
    html_dir.mkdir(parents=True, exist_ok=True)
    if not json_dir.is_dir():
        raise RuntimeError(f"JSON 会话目录不存在：{json_dir}")

    records = {}
    written = 0
    html_messages = 0
    fallback_messages = 0
    failures = []
    json_files = sorted(json_dir.glob("*.json"))
    if not json_files:
        raise RuntimeError(f"没有找到已导出的 session JSON：{json_dir}")

    for json_path in json_files:
        try:
            record = json.loads(json_path.read_text(encoding="utf-8"))
            if not isinstance(record, dict) or not isinstance(record.get("messages"), list):
                raise ValueError("不是有效的 conversation JSON")
            cid = str(record.get("conversation_id") or json_path.stem.split("__", 1)[0])
            title = str(record.get("title") or "Untitled conversation")
            for msg in record["messages"]:
                if str(msg.get("html") or "").strip(): html_messages += 1
                else: fallback_messages += 1
            html_name = f"{cid}__{safe_filename(title)}.html"
            write_html(html_dir / html_name, record)
            records[cid] = record
            written += 1
        except Exception as exc:
            failures.append((json_path.name, repr(exc)))

    index_path = write_html_library_index(out_dir, records)
    if failures:
        error_path = out_dir / "html_rerender_errors.jsonl"
        with error_path.open("w", encoding="utf-8") as fp:
            for name, err in failures:
                fp.write(json.dumps({"json_file": name, "error": err, "at": utc_now()}, ensure_ascii=False) + "\n")
        print(f"HTML 重建失败 {len(failures)} 个，详见: {error_path}")
    return written, html_messages, fallback_messages, index_path


def rerender_all_markdown(out_dir: Path) -> tuple[int, int, int]:
    """Rebuild Markdown files from existing per-conversation JSON only.

    No Edge connection, no sidebar scan, no network access.
    Returns: (sessions_written, messages_from_html, messages_fallback_text)
    """
    json_dir = out_dir / "json"
    markdown_dir = out_dir / "markdown"
    markdown_dir.mkdir(parents=True, exist_ok=True)

    if not json_dir.is_dir():
        raise RuntimeError(f"JSON 会话目录不存在：{json_dir}")

    written = 0
    html_messages = 0
    fallback_messages = 0
    failures = []

    json_files = sorted(json_dir.glob("*.json"))
    if not json_files:
        raise RuntimeError(f"没有找到已导出的 session JSON：{json_dir}")

    for json_path in json_files:
        try:
            record = json.loads(json_path.read_text(encoding="utf-8"))
            if not isinstance(record, dict) or not isinstance(record.get("messages"), list):
                raise ValueError("不是有效的 conversation JSON")

            for msg in record["messages"]:
                if str(msg.get("html") or "").strip():
                    html_messages += 1
                else:
                    fallback_messages += 1

            cid = str(record.get("conversation_id") or json_path.stem.split("__", 1)[0])
            title = str(record.get("title") or "Untitled conversation")
            md_name = f"{cid}__{safe_filename(title)}.md"
            write_markdown(markdown_dir / md_name, record)
            written += 1
        except Exception as exc:
            failures.append((json_path.name, repr(exc)))

    if failures:
        error_path = out_dir / "markdown_rerender_errors.jsonl"
        with error_path.open("w", encoding="utf-8") as fp:
            for name, err in failures:
                fp.write(json.dumps(
                    {"json_file": name, "error": err, "at": utc_now()},
                    ensure_ascii=False,
                ) + "\n")
        print(f"Markdown 重建失败 {len(failures)} 个，详见: {error_path}")

    return written, html_messages, fallback_messages



def _find_json_path_for_record(out_dir: Path, record: dict) -> Path:
    cid = str(record.get("conversation_id") or "")
    matches = sorted((out_dir / "json").glob(f"{cid}__*.json"))
    if matches:
        return matches[0]
    title = str(record.get("title") or "Untitled conversation")
    return out_dir / "json" / f"{cid}__{safe_filename(title)}.json"


async def repair_existing_content(
    page,
    out_dir: Path,
    *,
    repair_all: bool = False,
    repair_code_format: bool = False,
    limit: int = 0,
    delay_ms: int = 650,
) -> tuple[int, int, int]:
    """
    Refresh message text/html for already-exported JSON sessions.

    - Source URLs come ONLY from existing json/*.json.
    - No sidebar scan or manifest scan.
    - Existing generated_files metadata/files are preserved.
    - Existing JSON is backed up once before overwrite.
    - HTML + Markdown are regenerated immediately.
    """
    records = load_completed_records(out_dir)
    if not records:
        raise RuntimeError(f"没有找到已导出的 JSON session：{out_dir / 'json'}")

    candidates = []
    for cid, record in records.items():
        should_repair = False
        if repair_all:
            should_repair = True
        elif repair_code_format:
            # Intentionally refresh sessions that contain code blocks.
            # This is safer than trying to reconstruct lost line breaks offline.
            should_repair = record_has_code_blocks(record)
        else:
            should_repair = record_needs_content_repair(record)

        if should_repair:
            candidates.append((cid, record))

    if limit > 0:
        candidates = candidates[:limit]

    print(f"已导出 JSON session: {len(records)}")
    print(f"需要重新抓取内容: {len(candidates)}")
    if repair_code_format:
        print("当前模式只重新抓取包含代码块的已导出 session，并保存独立 code_blocks 数据，用于稳定恢复语言标签和多行代码。")
    elif not repair_all:
        print("当前模式只处理检测到空代码块/旧版代码丢失症状的 session。")
    if limit > 0:
        print(f"本次 --limit: {limit}")

    if not candidates:
        # Still rerender so old empty code shells are suppressed.
        rerender_all_html(out_dir)
        rerender_all_markdown(out_dir)
        return 0, 0, 0

    backup_dir = out_dir / (
        "json_before_v7_code_format_repair"
        if repair_code_format
        else "json_before_content_repair"
    )
    backup_dir.mkdir(parents=True, exist_ok=True)

    repaired = 0
    failed = 0
    skipped = 0

    original_url = page.url

    for n, (cid, record) in enumerate(candidates, 1):
        url = str(record.get("url") or "").strip()
        title = str(record.get("title") or cid)
        print(f"[{n}/{len(candidates)}] 修复 {title}")

        if not url.startswith("https://chatgpt.com/"):
            print("  !! JSON 中没有有效 ChatGPT URL，跳过")
            skipped += 1
            continue

        try:
            await page.goto(url, wait_until="domcontentloaded", timeout=60000)
            await wait_for_conversation(page)

            # Give syntax-highlight/code DOM a moment to finish rendering.
            await page.wait_for_timeout(900)
            try:
                last_message = page.locator('[data-message-author-role]').last
                if await last_message.count():
                    await last_message.scroll_into_view_if_needed(timeout=5000)
                    await page.wait_for_timeout(300)
            except Exception:
                pass

            messages = await extract_messages(page)
            if not messages:
                raise RuntimeError("页面没有提取到任何消息")

            json_path = _find_json_path_for_record(out_dir, record)
            backup_path = backup_dir / json_path.name
            if json_path.exists() and not backup_path.exists():
                shutil.copy2(json_path, backup_path)

            # Preserve metadata and downloaded generated_files. Only refresh messages.
            record["messages"] = messages
            record["content_repaired_at"] = utc_now()
            record["content_exporter_version"] = 7

            atomic_write_text(
                json_path,
                json.dumps(record, ensure_ascii=False, indent=2),
            )

            md_path = out_dir / "markdown" / f"{cid}__{safe_filename(title)}.md"
            html_path = out_dir / "html" / f"{cid}__{safe_filename(title)}.html"
            write_markdown(md_path, record)
            write_html(html_path, record)

            records[cid] = record
            repaired += 1
            print(f"  OK：消息 {len(messages)}")

        except Exception as exc:
            failed += 1
            print(f"  !! 修复失败: {exc}")

        if delay_ms > 0:
            await page.wait_for_timeout(delay_ms)

    rebuild_index(out_dir / "index.csv", records)
    rebuild_jsonl(out_dir / "conversations.jsonl", records)
    write_html_library_index(out_dir, records)

    # Restore the user's tab.
    if original_url and original_url != "about:blank":
        try:
            await page.goto(original_url, wait_until="domcontentloaded", timeout=30000)
        except Exception:
            pass

    return repaired, failed, skipped



def _native_snapshot_name(record: dict) -> str:
    cid = str(record.get("conversation_id") or "unknown")
