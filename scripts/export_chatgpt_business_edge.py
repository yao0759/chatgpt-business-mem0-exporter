async def scan_select_and_download_library(page, out_dir: Path, max_rounds: int = 500):
    """Scan /library, select every file except TXT/images, then download selection.

    Robust V8.3.3 implementation:
    - Scans all text nodes for valid file extensions (pdf, docx, xlsx, pptx, zip, py, json, etc.).
    - Detects files regardless of pre-matched control elements (prevents 0 files scan result).
    - Supports batch selection + ZIP download as well as 4-level fallback individual file downloads.
    """
    if "/library" not in (page.url or "").lower():
        try:
            await page.goto(CHATGPT_ORIGIN + "/library", wait_until="domcontentloaded", timeout=60000)
        except Exception:
            pass

    try:
        await page.wait_for_selector("main, body", timeout=10000)
    except Exception:
        pass
    await page.wait_for_timeout(3000)

    found: dict[str, dict] = {}
    unchanged_rounds = 0
    last_count = 0

    for scan_round in range(1, max_rounds + 1):
        rows = await page.evaluate(
            r"""
            () => {
              const EXT_RE = /\.(pdf|docx?|xlsx?|pptx?|txt|csv|zip|tar|gz|7z|rar|png|jpe?g|webp|gif|mp3|mp4|json|py|js|ts|html|css|sh|bat|md|ipynb|rs|cpp|c|h|java|go)$/i;
              const SIZE_RE = /^\d+(\.\d+)?\s*(B|KB|MB|GB|TB|bytes?)$/i;
              const DATE_RE = /^\d{4}[-\/]\d{2}[-\/]\d{2}/;

              const controls = 'input[type="checkbox"], [role="checkbox"], button[aria-checked], [class*="checkbox" i], svg[class*="check" i]';
              const dl_controls = 'button[aria-label*="download" i], button[aria-label*="下载" i], button[title*="下载" i], button[title*="download" i], a[download], a[href*="/files/"], a[href*="oaiusercontent"]';

              const result = [];
              const seen = new Set();
              const main = document.querySelector('main') || document.body;

              // 1. Scan links with download attributes or file URLs
              const links = Array.from(main.querySelectorAll('a[href]'));
              for (const a of links) {
                const href = a.getAttribute('href') || '';
                const text = (a.innerText || a.textContent || '').trim();
                if (EXT_RE.test(text) || EXT_RE.test(href) || href.includes('/backend-api/files') || href.includes('files.oaiusercontent.com')) {
                  let name = text;
                  const match = line_match = text.match(/([^\s\/\\:]+\.(?:pdf|docx?|xlsx?|pptx?|txt|csv|zip|tar|gz|7z|rar|png|jpe?g|webp|gif|mp3|mp4|json|py|js|ts|html|css|sh|bat|md|ipynb|rs|cpp|c|h|java|go))/i);
                  if (match) {
                    name = match[1];
                  } else if (!name && href) {
                    try {
                      const u = new URL(href, location.href);
                      name = u.pathname.split('/').pop() || '';
                    } catch(e) {}
                  }
                  name = (name || '').replace(/[，。；：、]+$/, '').trim();
                  if (name && name.length <= 150 && !SIZE_RE.test(name) && !DATE_RE.test(name)) {
                    const key = name.toLowerCase();
                    if (!seen.has(key)) {
                      seen.add(key);
                      result.push({
                        name: name,
                        checked: false,
                        has_checkbox: false,
                        has_download_btn: true,
                        has_download_link: true,
                        href: href
                      });
                    }
                  }
                }
              }

              // 2. Scan interactive elements / rows / table cells
              const all = Array.from(main.querySelectorAll('tr, [role="row"], li, div, p, span'));
              for (const el of all) {
                if (el.children.length > 15) continue;
                const text = (el.innerText || el.textContent || '').trim();
                if (!text || text.length > 300) continue;

                const lines = text.split('\n').map(s => s.trim()).filter(Boolean);
                for (const line of lines) {
                  const match = line.match(/([^\s\/\\:]+\.(?:pdf|docx?|xlsx?|pptx?|txt|csv|zip|tar|gz|7z|rar|png|jpe?g|webp|gif|mp3|mp4|json|py|js|ts|html|css|sh|bat|md|ipynb|rs|cpp|c|h|java|go))/i);
                  if (!match) continue;

                  const name = match[1].trim().replace(/[，。；：、]+$/, '');
                  if (!name || name.length < 3 || name.length > 150) continue;
                  if (SIZE_RE.test(name) || DATE_RE.test(name) || /^\d+(\.\d+)?$/.test(name)) continue;

                  const key = name.toLowerCase();
                  if (seen.has(key)) continue;

                  let root = el;
                  let checkbox = null;
                  let dl_btn = null;
                  for (let i = 0; i < 7 && root; i++, root = root.parentElement) {
                    if (!checkbox && root.querySelector) {
                      checkbox = root.querySelector(controls);
                    }
                    if (!dl_btn && root.querySelector) {
                      dl_btn = root.querySelector(dl_controls);
                    }
                    if (checkbox && dl_btn) break;
                  }

                  seen.add(key);
                  result.push({
                    name: name,
                    checked: checkbox ? (checkbox.checked === true || checkbox.getAttribute('aria-checked') === 'true') : false,
                    has_checkbox: !!checkbox,
                    has_download_btn: !!dl_btn
                  });
                }
              }
              return result;
            }
            """
        )

        for row in rows:
            name = str(row.get("name") or "").strip()
            if not name:
                continue
            key = name.casefold()
            item = found.setdefault(key, {
                "filename": name,
                "excluded": library_file_is_excluded(name),
                "selected": False,
                "has_checkbox": row.get("has_checkbox", False),
                "has_download_btn": row.get("has_download_btn", False),
                "has_download_link": row.get("has_download_link", False),
                "href": row.get("href", ""),
            })
            if item["excluded"]:
                item["selected"] = False
                continue

            if row.get("checked"):
                item["selected"] = True
                continue

            if row.get("has_checkbox") and not item["selected"]:
                clicked = await page.evaluate(
                    r"""
                    (wanted) => {
                      const controls = 'input[type="checkbox"], [role="checkbox"], button[aria-checked], [class*="checkbox" i], svg[class*="check" i]';
                      const nodes = Array.from(document.querySelectorAll('main *'));
                      const el = nodes.find(x => ((x.innerText || x.textContent || '').trim()).includes(wanted));
                      if (!el) return false;
                      let root = el;
                      for (let i = 0; i < 7 && root; i++, root = root.parentElement) {
                        const box = root.querySelector && root.querySelector(controls);
                        if (box) { box.click(); return true; }
                      }
                      return false;
                    }
                    """,
                    name,
                )
                if clicked:
                    item["selected"] = True
                    await page.wait_for_timeout(40)
                else:
                    item["selected"] = True
            else:
                item["selected"] = True

        if len(found) == last_count:
            unchanged_rounds += 1
        else:
            unchanged_rounds = 0
            last_count = len(found)

        moved = await page.evaluate(
            r"""
            () => {
              const candidates = Array.from(document.querySelectorAll('main, main *'))
                .filter(x => x.scrollHeight > x.clientHeight + 50);
              candidates.sort((a,b) => (b.clientHeight*b.clientWidth) - (a.clientHeight*a.clientWidth));
              const scroller = candidates[0] || document.scrollingElement;
              if (!scroller) return false;
              const before = scroller.scrollTop;
              scroller.scrollTop = Math.min(scroller.scrollTop + Math.max(scroller.clientHeight * .85, 500), scroller.scrollHeight);
              return scroller.scrollTop > before;
            }
            """
        )
        await page.wait_for_timeout(450)
        if (not moved and unchanged_rounds >= 4) or unchanged_rounds >= 10:
            break

    if not found:
        try:
            debug_html = await page.content()
            debug_path = out_dir / "library_debug_dom.html"
            atomic_write_text(debug_path, debug_html)
            print(f"\n[调试信息] 未扫描到任何资料库文件，DOM 结构已保存至: {debug_path}")
        except Exception:
            pass

    manifest = {
        "scanned_at": utc_now(),
        "library_url": page.url,
        "file_count": len(found),
        "selected_count": sum(1 for x in found.values() if x["selected"]),
        "excluded_count": sum(1 for x in found.values() if x["excluded"]),
        "files": list(found.values()),
    }
    manifest_path = out_dir / "library_file_scan.json"
    atomic_write_text(manifest_path, json.dumps(manifest, ensure_ascii=False, indent=2))

    selected_items = [x for x in found.values() if x["selected"]]
    if not selected_items:
        return manifest, manifest_path, []

    download_dir = out_dir / "library_downloads"
    download_dir.mkdir(parents=True, exist_ok=True)
    downloads = []

    # 1. Hover over each selected row to expose and click its checkbox (triggers top floating download bar)
    for item in selected_items:
        fname = item["filename"]
        try:
            await page.evaluate(
                r"""
                (wanted) => {
                  const main = document.querySelector('main') || document.body;
                  const rows = Array.from(main.querySelectorAll('tr, [role="row"], li, div'));
                  const row = rows.find(r => {
                    const txt = (r.innerText || r.textContent || '').trim();
                    return txt.includes(wanted) && r.children.length < 25;
                  });
                  if (!row) return false;

                  // Hover over row to force hidden checkbox to display
                  ['mouseenter', 'mouseover', 'mousemove'].forEach(evt => {
                    row.dispatchEvent(new MouseEvent(evt, { bubbles: true, cancelable: true, view: window }));
                  });

                  const controls = 'input[type="checkbox"], [role="checkbox"], button[aria-checked], [class*="checkbox" i], svg[class*="check" i]';
                  const box = row.querySelector(controls) || (row.parentElement ? row.parentElement.querySelector(controls) : null);
                  if (box) {
                    const isChecked = box.checked === true || box.getAttribute('aria-checked') === 'true' || box.classList.contains('checked');
                    if (!isChecked) {
                      box.click();
                      return true;
                    }
                  }
                  return false;
                }
                """,
                fname,
            )
            await page.wait_for_timeout(60)
        except Exception:
            pass

    batch_downloaded = False
    try:
        # Search for batch download button in floating toolbar or page header
        btn_element = await page.evaluate_handle(
            r"""
            () => {
              const buttons = Array.from(document.querySelectorAll('button, a, [role="button"]'));
              for (const b of buttons) {
                const text = (b.innerText || b.textContent || '').trim().toLowerCase();
                const aria = (b.getAttribute('aria-label') || '').toLowerCase();
                const title = (b.getAttribute('title') || '').toLowerCase();
                if ((text.includes('下载') || text.includes('download') || aria.includes('下载') || aria.includes('download') || title.includes('下载') || title.includes('download')) && b.getBoundingClientRect().height > 0) {
                  return b;
                }
              }
              return null;
            }
            """
        )
        if btn_element and await btn_element.as_element():
            btn = btn_element.as_element()
            async with page.expect_download(timeout=30000) as info:
                await btn.click(timeout=10000)
            download = await info.value
            path = unique_path(download_dir, download.suggested_filename or "library_download.zip")
            await download.save_as(str(path))
            downloads.append(str(path))
            batch_downloaded = True
            print(f"成功触发批量 ZIP 下载: {path.name}")
    except Exception as exc:
        manifest["batch_download_error"] = repr(exc)

    if not batch_downloaded:
        print(f"\n批量 ZIP 下载未触发，切换为单文件逐个下载模式（共 {len(selected_items)} 个待下载文件）...")
        for item in selected_items:
            fname = item["filename"]
            print(f"  正在下载: {fname}...", end="", flush=True)
            try:
                downloaded_file = await download_library_item_directly(page, fname, download_dir)
                if downloaded_file:
                    downloads.append(str(downloaded_file))
                    print(" OK")
                else:
                    print(" 失败 (未找到下载控件)")
            except Exception as e:
                print(f" 失败 ({e})")

    return manifest, manifest_path, downloads


