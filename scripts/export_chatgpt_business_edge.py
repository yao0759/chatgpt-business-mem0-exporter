async def detect_title(page, fallback: str) -> str:
    # Page title is usually the least fragile source.
    try:
        title = (await page.title()).strip()
        title = re.sub(r"\s*[\-–—]\s*ChatGPT\s*$", "", title, flags=re.I).strip()
        if title and title.lower() != "chatgpt":
            return title
    except Exception:
        pass
    return fallback or "Untitled conversation"


async def direct_download(context, href: str, preferred_name: str | None, directory: Path):
    if not href or href.startswith(("javascript:", "blob:", "sandbox:")):
        return None

    url = urljoin(CHATGPT_ORIGIN + "/", href)
    if not url.lower().startswith(("http://", "https://")):
        return None

    try:
        response = await context.request.get(url, timeout=25000, fail_on_status_code=False)
        if not response.ok:
            return None

        headers = response.headers
        content_type = (headers.get("content-type") or "").lower()
        disposition = headers.get("content-disposition") or ""
        body = await response.body()

        # Avoid accidentally saving normal web pages/citation links.
        has_attachment_header = "attachment" in disposition.lower() or "filename=" in disposition.lower()
        looks_binary = not content_type.startswith("text/html")
        if not (has_attachment_header or looks_binary or FILE_EXT_RE.search(url)):
            return None

        name = (
            parse_content_disposition_filename(disposition)
            or preferred_name
            or guess_name_from_url(str(response.url))
            or guess_name_from_url(url)
        )

        if not name:
            ext = mimetypes.guess_extension(content_type.split(";", 1)[0].strip()) or ".bin"
            name = "generated_file" + ext

        path = unique_path(directory, name)
        path.write_bytes(body)
        return {
            "local_path": str(path),
            "filename": path.name,
            "size": len(body),
            "sha256": sha256_file(path),
            "source": "http",
            "source_url": url,
            "content_type": content_type,
        }
    except Exception:
        return None


async def click_download(page, element, preferred_name: str | None, directory: Path):
    try:
        async with page.expect_download(timeout=7000) as info:
            await element.click(timeout=5000)
        download = await info.value
        name = preferred_name or download.suggested_filename or "generated_file"
        path = unique_path(directory, name)
        await download.save_as(str(path))
        size = path.stat().st_size
        return {
            "local_path": str(path),
            "filename": path.name,
            "size": size,
            "sha256": sha256_file(path),
            "source": "click",
            "source_url": None,
            "content_type": None,
        }
    except Exception:
        return None


async def download_generated_files(page, context, conversation_id: str, output_files_root: Path):
    """
    Download files only from assistant messages, which intentionally excludes user uploads.
    """
    root = output_files_root / conversation_id
    root.mkdir(parents=True, exist_ok=True)

    assistant_nodes = page.locator('[data-message-author-role="assistant"]')
    count = await assistant_nodes.count()
    saved = []
    seen_sha256 = set()
    seen_signature = set()

    for assistant_index in range(count):
        node = assistant_nodes.nth(assistant_index)
        msg_dir = root / f"assistant_{assistant_index + 1:03d}"
        msg_dir.mkdir(parents=True, exist_ok=True)

        # 1) Anchors inside assistant turn.
        anchors = node.locator("a[href]")
        for j in range(await anchors.count()):
            a = anchors.nth(j)
            try:
                href = (await a.get_attribute("href") or "").strip()
                text = re.sub(r"\s+", " ", (await a.inner_text()).strip())
                download_attr = await a.get_attribute("download")
            except Exception:
                continue

            if not is_file_candidate(text, href, download_attr):
                continue

            signature = (assistant_index, href, text, download_attr or "")
            if signature in seen_signature:
                continue
            seen_signature.add(signature)

            preferred = candidate_file_name(text, href, download_attr)
            result = await direct_download(context, href, preferred, msg_dir)
            if result is None:
                result = await click_download(page, a, preferred, msg_dir)

            if result:
                if result["sha256"] in seen_sha256:
                    try:
                        Path(result["local_path"]).unlink(missing_ok=True)
                    except Exception:
                        pass
                    continue
                seen_sha256.add(result["sha256"])
                result.update({
                    "assistant_message_index": assistant_index,
                    "link_text": text,
                })
                saved.append(result)

        # 2) Explicit Download/下载 buttons inside assistant turn.
        buttons = node.locator("button")
        for j in range(await buttons.count()):
            b = buttons.nth(j)
            try:
                text = re.sub(r"\s+", " ", (await b.inner_text()).strip())
                aria = await b.get_attribute("aria-label") or ""
                title = await b.get_attribute("title") or ""
                label = " ".join([text, aria, title]).strip()
            except Exception:
                continue

            if not DOWNLOAD_WORD_RE.search(label):
                continue

            signature = (assistant_index, "button", label, str(j))
            if signature in seen_signature:
                continue
            seen_signature.add(signature)

            preferred = candidate_file_name(label, "", None)
            result = await click_download(page, b, preferred, msg_dir)
            if result:
                if result["sha256"] in seen_sha256:
                    try:
                        Path(result["local_path"]).unlink(missing_ok=True)
                    except Exception:
                        pass
                    continue
                seen_sha256.add(result["sha256"])
                result.update({
                    "assistant_message_index": assistant_index,
                    "link_text": label,
                })
                saved.append(result)

        # Remove empty message directory.
        try:
            if not any(msg_dir.iterdir()):
                msg_dir.rmdir()
        except Exception:
            pass

    try:
        if root.exists() and not any(root.iterdir()):
            root.rmdir()
    except Exception:
        pass

    return saved



