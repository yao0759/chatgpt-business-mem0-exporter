class _HtmlNode:
    __slots__ = ("tag", "attrs", "children")

    def __init__(self, tag: str = "", attrs=None):
        self.tag = (tag or "").lower()
        self.attrs = dict(attrs or [])
        self.children = []


class _HtmlTreeParser(HTMLParser):
    VOID_TAGS = {
        "area", "base", "br", "col", "embed", "hr", "img", "input",
        "link", "meta", "param", "source", "track", "wbr",
    }

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = _HtmlNode("root")
        self.stack = [self.root]
        self.skip_depth = 0

    def handle_starttag(self, tag, attrs):
        tag = tag.lower()
        if self.skip_depth:
            self.skip_depth += 1
            return
        if tag in {"script", "style", "noscript"}:
            self.skip_depth = 1
            return
        node = _HtmlNode(tag, attrs)
        self.stack[-1].children.append(node)
        if tag not in self.VOID_TAGS:
            self.stack.append(node)

    def handle_startendtag(self, tag, attrs):
        if self.skip_depth:
            return
        self.stack[-1].children.append(_HtmlNode(tag.lower(), attrs))

    def handle_endtag(self, tag):
        tag = tag.lower()
        if self.skip_depth:
            self.skip_depth -= 1
            return

        # ChatGPT HTML should be well formed, but tolerate mismatched wrappers.
        for i in range(len(self.stack) - 1, 0, -1):
            if self.stack[i].tag == tag:
                del self.stack[i:]
                return

    def handle_data(self, data):
        if not self.skip_depth and data:
            self.stack[-1].children.append(data)


def _node_attr(node: _HtmlNode, name: str) -> str:
    value = node.attrs.get(name, "")
    return str(value or "")


def _node_text(node, preserve_breaks: bool = True) -> str:
    if isinstance(node, str):
        return node

    out = []
    for child in node.children:
        if isinstance(child, _HtmlNode) and child.tag == "br" and preserve_breaks:
            out.append("\n")
        else:
            out.append(_node_text(child, preserve_breaks=preserve_breaks))
    return "".join(out)


def _walk_nodes(node):
    if isinstance(node, str):
        return
    yield node
    for child in node.children:
        if isinstance(child, _HtmlNode):
            yield from _walk_nodes(child)


def _find_first(node: _HtmlNode, tag: str):
    for candidate in _walk_nodes(node):
        if candidate.tag == tag:
            return candidate
    return None


def _normalize_language(value: str) -> str:
    value = html_lib.unescape(value or "").strip().lower()
    value = re.sub(r"^[^a-z0-9+#.-]+|[^a-z0-9+#. -]+$", "", value)
    if value in _LANGUAGE_ALIASES:
        return _LANGUAGE_ALIASES[value]

    # language-python / lang-python / highlight-source-python
    for pattern in (
        r"(?:^|[\s_-])language[-_:]?([a-z0-9+#.]+)",
        r"(?:^|[\s_-])lang[-_:]?([a-z0-9+#.]+)",
        r"(?:^|[\s_-])source[-_:]?([a-z0-9+#.]+)",
    ):
        m = re.search(pattern, value)
        if m:
            token = m.group(1)
            return _LANGUAGE_ALIASES.get(token, token)

    # A bare short token in an attribute can itself be the language.
    for token in re.split(r"[\s,;]+", value):
        if token in _LANGUAGE_ALIASES:
            return _LANGUAGE_ALIASES[token]
    return ""


def _infer_code_language(pre: _HtmlNode, code: _HtmlNode | None) -> str:
    # 1) Explicit attributes/classes on <code> or <pre>.
    for node in (code, pre):
        if node is None:
            continue
        for key in ("data-language", "data-lang", "lang", "class"):
            lang = _normalize_language(_node_attr(node, key))
            if lang:
                return lang

    # 2) ChatGPT commonly renders a language label as a non-code child in <pre>.
    labels = []
    for child in pre.children:
        if child is code:
            continue
        if isinstance(child, str):
            labels.append(child)
        elif isinstance(child, _HtmlNode):
            # Ignore controls but inspect small textual labels.
            if child.tag in {"button", "svg"}:
                continue
            txt = re.sub(r"\s+", " ", _node_text(child)).strip()
            if txt and len(txt) <= 40:
                labels.append(txt)

    for label in labels:
        for part in re.split(r"[\s|/]+", label):
            lang = _normalize_language(part)
            if lang:
                return lang

    return ""


def _choose_fence(code_text: str) -> str:
    runs = [len(x) for x in re.findall(r"`+", code_text or "")]
    return "`" * max(3, (max(runs) + 1) if runs else 3)


def _inline_code(text: str) -> str:
    text = (text or "").replace("\r\n", "\n").replace("\r", "\n")
    if "\n" in text:
        # Inline <code> should rarely contain newlines; preserve it safely.
        fence = _choose_fence(text)
        return f"{fence}\n{text}\n{fence}"

    runs = [len(x) for x in re.findall(r"`+", text)]
    ticks = "`" * max(1, (max(runs) + 1) if runs else 1)
    # Markdown requires padding when code starts/ends with a backtick or space.
    pad = " " if text.startswith(("`", " ")) or text.endswith(("`", " ")) else ""
    return f"{ticks}{pad}{text}{pad}{ticks}"


def _escape_table_cell(text: str) -> str:
    text = re.sub(r"\s+", " ", text or "").strip()
    return text.replace("|", r"\|")


def _render_table(node: _HtmlNode) -> str:
    rows = []
    for tr in _walk_nodes(node):
        if tr.tag != "tr":
            continue
        cells = []
        for child in tr.children:
            if isinstance(child, _HtmlNode) and child.tag in {"th", "td"}:
                cells.append(_escape_table_cell(_render_node(child).strip()))
        if cells:
            rows.append(cells)

    if not rows:
        return ""

    width = max(len(r) for r in rows)
    rows = [r + [""] * (width - len(r)) for r in rows]
    header = rows[0]
    lines = [
        "| " + " | ".join(header) + " |",
        "| " + " | ".join(["---"] * width) + " |",
    ]
    for row in rows[1:]:
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines) + "\n\n"


def _render_list(node: _HtmlNode, ordered: bool, depth: int = 0) -> str:
    lines = []
    number = 1

    for child in node.children:
        if not isinstance(child, _HtmlNode) or child.tag != "li":
            continue

        body_parts = []
        nested_lists = []
        for item in child.children:
            if isinstance(item, _HtmlNode) and item.tag in {"ul", "ol"}:
                nested_lists.append(item)
            else:
                body_parts.append(_render_node(item))

        body = _cleanup_inline("".join(body_parts))
        prefix = f"{number}. " if ordered else "- "
        indent = "    " * depth

        body_lines = body.splitlines() or [""]
        lines.append(indent + prefix + body_lines[0])
        continuation_indent = indent + " " * len(prefix)
        for extra in body_lines[1:]:
            lines.append(continuation_indent + extra)

        for nested in nested_lists:
            nested_md = _render_list(nested, nested.tag == "ol", depth + 1).rstrip()
            if nested_md:
                lines.extend(nested_md.splitlines())

        number += 1

    return "\n".join(lines) + ("\n\n" if lines else "")


def _cleanup_inline(value: str) -> str:
    value = value.replace("\r\n", "\n").replace("\r", "\n")
    # Collapse horizontal whitespace but preserve explicit line breaks.
    value = re.sub(r"[ \t\f\v]+", " ", value)
    value = re.sub(r" *\n *", "\n", value)
    return value.strip()


def _render_pre(node: _HtmlNode) -> str:
    code_node = _find_first(node, "code")
    source = code_node if code_node is not None else node
    code = _node_text(source, preserve_breaks=True)
    code = code.replace("\r\n", "\n").replace("\r", "\n")
    code = code.strip("\n")

    # If the label was actually included in the code text, remove only a first
    # line that is an exact known language token.
    language = _infer_code_language(node, code_node)
    code_lines = code.splitlines()
    if code_lines:
        first_lang = _normalize_language(code_lines[0].strip())
        if first_lang and len(code_lines[0].strip()) <= 20 and len(code_lines) > 1:
            if not language:
                language = first_lang
            code = "\n".join(code_lines[1:])

    fence = _choose_fence(code)
    return f"{fence}{language}\n{code}\n{fence}\n\n"


def _render_node(node) -> str:
    if isinstance(node, str):
        return node

    tag = node.tag

    if tag == "root":
        return "".join(_render_node(c) for c in node.children)
    if tag in {"script", "style", "noscript", "button", "svg"}:
        return ""
    if tag == "br":
        return "\n"
    if tag == "hr":
        return "\n\n---\n\n"
    if tag == "pre":
        return _render_pre(node)
    if tag == "code":
        return _inline_code(_node_text(node, preserve_breaks=True))
    if tag in {"strong", "b"}:
        body = _cleanup_inline("".join(_render_node(c) for c in node.children))
        return f"**{body}**" if body else ""
    if tag in {"em", "i"}:
        body = _cleanup_inline("".join(_render_node(c) for c in node.children))
        return f"*{body}*" if body else ""
    if tag in {"del", "s", "strike"}:
        body = _cleanup_inline("".join(_render_node(c) for c in node.children))
        return f"~~{body}~~" if body else ""
    if tag == "a":
        body = _cleanup_inline("".join(_render_node(c) for c in node.children))
        href = _node_attr(node, "href").strip()
        title = _node_attr(node, "title").strip()
        if not body:
            body = href
        if not href or href.startswith(("javascript:", "#")):
            return body
        suffix = f' "{title.replace(chr(34), chr(39))}"' if title else ""
        return f"[{body}]({href}{suffix})"
    if tag == "img":
        alt = _node_attr(node, "alt").strip()
        src = _node_attr(node, "src").strip()
        return f"![{alt}]({src})" if src else alt
    if tag in {"h1", "h2", "h3", "h4", "h5", "h6"}:
        level = int(tag[1])
        body = _cleanup_inline("".join(_render_node(c) for c in node.children))
        return f"{'#' * level} {body}\n\n" if body else ""
    if tag == "blockquote":
        body = cleanup_markdown("".join(_render_node(c) for c in node.children)).strip()
        if not body:
            return ""
        return "\n".join("> " + line if line else ">" for line in body.splitlines()) + "\n\n"
    if tag == "ul":
        return _render_list(node, ordered=False)
    if tag == "ol":
        return _render_list(node, ordered=True)
    if tag == "li":
        return _cleanup_inline("".join(_render_node(c) for c in node.children))
    if tag == "table":
        return _render_table(node)
    if tag == "p":
        body = "".join(_render_node(c) for c in node.children).strip()
        return body + "\n\n" if body else ""

    # Preserve pasted/user text from ChatGPT's whitespace-preserving wrappers.
    cls = _node_attr(node, "class").lower()
    if "whitespace-pre-wrap" in cls or "whitespace-pre" in cls:
        body = "".join(_render_node(c) for c in node.children)
        return body.rstrip() + "\n\n" if body.strip() else ""

    body = "".join(_render_node(c) for c in node.children)
    if tag in _BLOCK_TAGS:
        return body.rstrip() + "\n\n" if body.strip() else ""
    return body


def cleanup_markdown(markdown: str) -> str:
    """Normalize whitespace without altering fenced-code contents."""
    markdown = (markdown or "").replace("\r\n", "\n").replace("\r", "\n")
    lines = markdown.splitlines()

    out = []
    in_fence = False
    fence_char = ""
    fence_len = 0
    blank_count = 0

    for line in lines:
        fence_match = re.match(r"^\s*(`{3,}|~{3,})(.*)$", line)

        if in_fence:
            out.append(line.rstrip())
            if fence_match:
                token = fence_match.group(1)
                if token[0] == fence_char and len(token) >= fence_len:
                    in_fence = False
            continue

        if fence_match:
            token = fence_match.group(1)
            in_fence = True
            fence_char = token[0]
            fence_len = len(token)
            out.append(line.rstrip())
            blank_count = 0
            continue

        stripped = line.rstrip()

        # Drop code-block chrome left by some ChatGPT DOM versions.
        if stripped.strip().lower() in _UI_ONLY_LINES:
            continue

        if not stripped.strip():
            blank_count += 1
            if blank_count <= 1:
                out.append("")
        else:
            blank_count = 0
            out.append(stripped)

    # Remove a standalone language label immediately preceding a fenced block.
    cleaned = []
    i = 0
    while i < len(out):
        current = out[i]
        normalized = _normalize_language(current.strip())
        if normalized and current.strip().lower() in _LANGUAGE_ALIASES:
            j = i + 1
            while j < len(out) and not out[j].strip():
                j += 1
            if j < len(out) and re.match(r"^\s*`{3,}", out[j]):
                i += 1
                while i < j:
                    i += 1
                continue
        cleaned.append(current)
        i += 1

    return "\n".join(cleaned).strip() + "\n"


def html_to_markdown(html: str, fallback_text: str = "") -> str:
    if not html or not html.strip():
        return cleanup_markdown(fallback_text)

    try:
        parser = _HtmlTreeParser()
        parser.feed(html)
        parser.close()
        rendered = cleanup_markdown(_render_node(parser.root))
        if rendered.strip():
            return rendered
    except Exception:
        # A malformed historical HTML fragment should never prevent the entire
        # session from being re-rendered.
        pass

    return cleanup_markdown(fallback_text)


def message_to_markdown(msg: dict) -> str:
    return html_to_markdown(
        str(msg.get("html") or ""),
        fallback_text=str(msg.get("text") or ""),
    ).rstrip()


def write_markdown(path: Path, record: dict):
    files_by_message: dict[int, list[dict]] = {}
    for f in record.get("generated_files", []):
        try:
            key = int(f["assistant_message_index"])
        except Exception:
            continue
        files_by_message.setdefault(key, []).append(f)

    lines = [
        f"# {record.get('title') or 'Untitled conversation'}",
        "",
        f"- URL: {record.get('url', '')}",
        f"- Exported at: {record.get('exported_at', '')}",
        f"- Messages: {len(record.get('messages', []))}",
        f"- Assistant-generated files saved: {len(record.get('generated_files', []))}",
        "",
        "---",
        "",
    ]

    assistant_counter = -1
    for i, msg in enumerate(record.get("messages", []), 1):
        role = str(msg.get("role", "unknown"))
        if role == "assistant":
            assistant_counter += 1

        display_role = {
            "user": "User",
            "assistant": "Assistant",
            "system": "System",
            "tool": "Tool",
        }.get(role, role.title())

        lines.extend([
            f"## {i}. {display_role}",
            "",
            message_to_markdown(msg),
            "",
        ])

        if role == "assistant" and assistant_counter in files_by_message:
            lines.extend(["### Generated files", ""])
            for f in files_by_message[assistant_counter]:
                filename = str(f.get("filename") or "generated_file")
                size = f.get("size", "?")
                digest = str(f.get("sha256") or "")
                rel = str(f.get("local_path") or "")

                # local_path may be absolute on Windows. Keep the stable file name
                # in Markdown and retain size/hash metadata.
                line = f"- `{filename}`  ({size} bytes"
                if digest:
                    line += f", SHA256 `{digest}`"
                line += ")"
                if rel:
                    line += f"  — `{rel}`"
                lines.append(line)
            lines.append("")

    atomic_write_text(path, cleanup_markdown("\n".join(lines)))



